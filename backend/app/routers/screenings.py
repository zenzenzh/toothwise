def _to_patient_out(screening: models.Screening) -> schemas.PatientScreeningOut:
    fused = [d for d in screening.detections if d.detection_set == "fused"]
    return schemas.PatientScreeningOut(
        id=screening.id,
        image_path=screening.image_path,
        image_width=screening.image_width,
        image_height=screening.image_height,
        risk_level=screening.risk_level,
        risk_score=screening.risk_score,
        created_at=screening.created_at,
        detections=fused,
        recommendations=screening.recommendations,
    )


def _resolve_image_path(image_path: str) -> Path:
    """
    Resolves a stored image_path to an on-disk file, refusing to serve
    anything outside UPLOAD_DIR even if image_path were ever somehow
    manipulated (path traversal defense-in-depth - image_path is normally
    server-generated by save_upload(), never taken from user input, but
    this makes that assumption explicit rather than implicit).
    """
    upload_root = Path(settings.UPLOAD_DIR).resolve()
    candidate = (upload_root / image_path).resolve()
    if upload_root not in candidate.parents and candidate != upload_root:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Image not found.")
    if not candidate.is_file():
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Image not found.")
    return candidate


def _restore_image_if_missing(screening: models.Screening) -> None:
    """If the photo is gone from disk (e.g. a host that wipes local storage
    on restart) but a database copy exists, write it back under UPLOAD_DIR.
    Same traversal guard as _resolve_image_path."""
    upload_root = Path(settings.UPLOAD_DIR).resolve()
    target = (upload_root / screening.image_path).resolve()
    if upload_root not in target.parents or target.is_file():
        return
    stored = screening.stored_image
    if stored is None:
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(stored.data)


def _image_file(screening: models.Screening) -> Path:
    _restore_image_if_missing(screening)
    return _resolve_image_path(screening.image_path)


@router.get("/screenings/mine", response_model=list[schemas.PatientScreeningOut])
def list_my_screenings(
    db: Session = Depends(get_db),
    current_patient: models.Patient = Depends(get_current_patient),
):
    """Patient portal - the logged-in patient's own screening history, newest first."""
    screenings = (
        db.query(models.Screening)
        .filter(models.Screening.patient_id == current_patient.id)
        .order_by(models.Screening.created_at.desc())
        .all()
    )
    return [_to_patient_out(s) for s in screenings]


@router.get("/screenings/self/{screening_id}", response_model=schemas.PatientScreeningOut)
def get_my_screening(
    screening_id: int,
    db: Session = Depends(get_db),
    current_patient: models.Patient = Depends(get_current_patient),
):
    """
    Patient portal - a single screening of the patient's own, with the
    annotated image and recommendations. 404s (not 403) if the screening
    belongs to someone else, so a patient can't tell the difference
    between "not yours" and "doesn't exist" by probing IDs.
    """
    screening = db.get(models.Screening, screening_id)
    if not screening or screening.patient_id != current_patient.id:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Screening not found.")
    return _to_patient_out(screening)


