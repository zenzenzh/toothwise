@router.get("/screenings/{screening_id}/compare", response_model=schemas.ModelComparisonOut)
def compare_models(
    screening_id: int,
    db: Session = Depends(get_db),
    _: models.Dentist = Depends(require_clinical),
):
    """
    Per-screening YOLOv8 vs YOLOv12 comparison: what each model detected
    on THIS image, how fast, and how often they independently agreed.

    This is descriptive runtime data, not accuracy/precision/recall/mAP -
    those require comparing against ground-truth labels, which a live
    patient photo doesn't have. For real accuracy metrics, run
    backend/training/evaluate_models.py against your labeled test set
    after training and use those numbers for your thesis's Chapter 4.
    """
    screening = db.get(models.Screening, screening_id)
    if not screening:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Screening not found.")

    v8_dets = [d for d in screening.detections if d.detection_set == "yolov8_raw"]
    v12_dets = [d for d in screening.detections if d.detection_set == "yolov12_raw"]
    fused_count = sum(1 for d in screening.detections if d.detection_set == "fused")

    def avg_conf(dets):
        return round(sum(d.confidence for d in dets) / len(dets), 4) if dets else None

    def iou(a, b):
        ix1, iy1 = max(a.x1, b.x1), max(a.y1, b.y1)
        ix2, iy2 = min(a.x2, b.x2), min(a.y2, b.y2)
        if ix2 <= ix1 or iy2 <= iy1:
            return 0.0
        inter = (ix2 - ix1) * (iy2 - iy1)
        area_a = (a.x2 - a.x1) * (a.y2 - a.y1)
        area_b = (b.x2 - b.x1) * (b.y2 - b.y1)
        union = area_a + area_b - inter
        return inter / union if union > 0 else 0.0

    agreement_count = sum(
        1 for a in v8_dets for b in v12_dets
        if a.label == b.label and iou(a, b) >= 0.5
    )

    return schemas.ModelComparisonOut(
        screening_id=screening.id,
        yolov8=schemas.ModelStatsOut(
            detection_count=len(v8_dets),
            avg_confidence=avg_conf(v8_dets),
            inference_ms=screening.yolov8_ms,
            detections=v8_dets,
        ),
        yolov12=schemas.ModelStatsOut(
            detection_count=len(v12_dets),
            avg_confidence=avg_conf(v12_dets),
            inference_ms=screening.yolov12_ms,
            detections=v12_dets,
        ),
        fused_count=fused_count,
        agreement_count=agreement_count,
    )


