@router.post(
    "/patients/{patient_id}/screening",
    response_model=schemas.ScreeningDetailOut,
    status_code=status.HTTP_201_CREATED,
)
def create_screening(
    patient_id: int,
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
    current: models.Dentist = Depends(require_clinical),
):
    patient = db.get(models.Patient, patient_id)
    if not patient:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Patient not found.")

    if not settings.DETECTION_ENABLED:
        raise HTTPException(
            status.HTTP_503_SERVICE_UNAVAILABLE,
            "AI screening is temporarily unavailable.",
        )

    image_path, width, height = save_upload(file, patient_id)

    # --- 1. Dual YOLOv8 / YOLOv12 ensemble inference ---
    detector = get_detector()
    result = detector.detect(image_path)
    raw_detections = result["detections"]  # fused - drives risk score below

    # --- 2. Rule-based risk score (auditable, testable) ---
    risk = compute_risk(raw_detections)

    # --- 3. KNN-driven prevention plan ---
    plan = generate_prevention_plan(raw_detections, patient.age)

    # --- 4. Persist everything ---
    screening = models.Screening(
        patient_id=patient_id,
        dentist_id=current.id,
        image_path=image_path,
        image_width=width,
        image_height=height,
        risk_level=risk.level,
        risk_score=risk.score,
        yolov8_ms=result["yolov8_ms"],
        yolov12_ms=result["yolov12_ms"],
    )
    db.add(screening)
    db.flush()  # get screening.id before adding children

    if settings.STORE_IMAGES_IN_DB:
        db.add(models.ScreeningImage(
            screening_id=screening.id,
            data=(Path(settings.UPLOAD_DIR) / image_path).read_bytes(),
        ))

    # Store all three detection sets - fused (drives the clinical result)
    # plus each model's raw, unfused output - so the app can render a
    # model-vs-model comparison, not just the final ensemble. detection_set
    # tags which pass each row belongs to, since source_model alone can't
    # disambiguate a fused single-model-agreement row from a raw row.
    for det in raw_detections:
        db.add(models.Detection(screening_id=screening.id, detection_set="fused", **det))
    for det in result["detections_v8"]:
        db.add(models.Detection(screening_id=screening.id, detection_set="yolov8_raw", **det))
    for det in result["detections_v12"]:
        db.add(models.Detection(screening_id=screening.id, detection_set="yolov12_raw", **det))

    for rec in plan:
        db.add(models.Recommendation(screening_id=screening.id, **rec))

    log_action(
        db, current, "screening.create", "screening", screening.id,
        f"patient_id={patient_id} risk={risk.level}:{risk.score}",
    )
    db.commit()
    db.refresh(screening)
    return screening


